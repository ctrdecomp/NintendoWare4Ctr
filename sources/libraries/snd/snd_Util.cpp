const void* Util::GetWaveFile(u32 waveArchiveId, u32 waveIndex,
    const SoundArchive& arc, const SoundArchivePlayer& player)
{
    SoundArchive::WaveArchiveInfo info;
    if (!arc.ReadWaveArchiveInfo(waveArchiveId, &info))
    {
        return NULL;
    }

    const void* warcFile = player.detail_GetFileAddress(info.fileId);

    if (warcFile == NULL)
    {
        return NULL;
    }

    WaveArchiveFileReader reader(warcFile, info.isLoadIndividual);
    const void* waveFile = reader.GetWaveFile( waveIndex );

    NW_WARNING(waveFile, "index(%d) in warc(0x%08x) is not loaded.", waveIndex, waveArchiveId);
    if (waveFile == NULL)
    {
        return NULL;
    }
    return waveFile;
}

