bool Util::IsLoadedWaveArchive(const void* bankFile,
    const SoundArchive& arc, const SoundArchiveLoader& mgr)
{
    BankFileReader bankFileReader(bankFile);
    const Util::WaveIdTable& table = bankFileReader.GetWaveIdTable();

    const Util::WaveId* pWaveId = table.GetWaveId(0);
    if(pWaveId == NULL)
    {
        return false;
    }
    const void* waveArchiveFile = mgr.detail_GetFileAddressByItemId(pWaveId->waveArchiveId);
    if(waveArchiveFile == NULL)
    {
        return false;
    }

    SoundArchive::WaveArchiveInfo warcInfo;
    bool isReadWarcInfo = arc.ReadWaveArchiveInfo(pWaveId->waveArchiveId, &warcInfo);
    NW_ASSERTMSG(isReadWarcInfo, "WARC(%08x) is invalid.", pWaveId->waveArchiveId);

    if(warcInfo.isLoadIndividual)
    {
        WaveArchiveFileReader reader(waveArchiveFile, true);
        for (u32 i = 0; i < table.GetCount(); i++)
        {
            if(!reader.IsLoaded(pWaveId->waveIndex))
            {
                return false;
            }
        }
    }
    return true;
}

bool Util::IsLoadedWaveArchive(const void* wsdFile, u32 index,
    const SoundArchive& arc, const SoundArchiveLoader& mgr)
{
    WaveSoundFileReader reader(wsdFile);
    WaveSoundNoteInfo noteInfo;
    bool isReadNoteInfo = reader.ReadNoteInfo(&noteInfo, index, 0);
    NW_ASSERT(isReadNoteInfo);

    const void* waveArchiveFile = mgr.detail_GetFileAddressByItemId(noteInfo.waveArchiveId);
    if (waveArchiveFile == NULL)
    {
        return false;
    }

    SoundArchive::WaveArchiveInfo warcInfo;
    bool isReadWarcInfo = arc.ReadWaveArchiveInfo(noteInfo.waveArchiveId, &warcInfo);
    NW_ASSERTMSG(isReadWarcInfo, "WARC(%08x) is invalid.", noteInfo.waveArchiveId);

    if (warcInfo.isLoadIndividual)
    {
        WaveArchiveFileReader warcReader(waveArchiveFile, true);
        if (!warcReader.IsLoaded(noteInfo.waveIndex))
        {
            return false;
        }
    }
    return true;
}

unsigned long Util::GetSampleByByte(unsigned long byte, SampleFormat format)
{
    unsigned long samples = 0;
    unsigned long frac;

    switch (format)
    {
    case SAMPLE_FORMAT_DSP_ADPCM:
        samples = (byte / 8) * 14;
        frac = (byte % 8);
        if (frac != 0)
        {
            samples += (frac - 1) * 2;
        }
        break;

    case SAMPLE_FORMAT_PCM_S8:
        samples = byte;
        break;

    case SAMPLE_FORMAT_PCM_S16:
        samples = (byte >> 1);
        break;

    default:
        NW_ASSERTMSG(false, "Invalid format\n");
        break;
    }

    return samples;
}

unsigned long Util::GetByteBySample(unsigned long samples, SampleFormat format)
{
    unsigned long byte = 0;
    unsigned long frac;

    switch (format)
    {
    case SAMPLE_FORMAT_DSP_ADPCM:
        byte = (samples / 14) * 8;
        frac = (samples % 14);
        if (frac != 0)
        {
            byte += ((frac + 1) >> 1) + 1;
        }
        break;
        
    case SAMPLE_FORMAT_PCM_S8:
        byte = samples;
        break;

    case SAMPLE_FORMAT_PCM_S16:
        byte = (samples << 1);
        break;

    default:
        NW_ASSERTMSG(false, "Invalid format\n");
        break;
    }
    
    return byte;
}

f32 Util::CalcPanRatio(f32 pan, const PanInfo& info) 
{
    pan = (ut::Clamp(pan, -1.0f, 1.0f) + 1.0f) / 2.0f;

    const f32* pTable = NULL;
    if (nw::snd::SoundSystem::GetOutputMode() == nw::snd::OUTPUT_MODE_SURROUND)
    {
        pTable = PanTableTableForSurround[info.curve];
    }
    else
    {
        pTable = PanTableTable[info.curve];
    }

    register f32 ratio = 0.0f;
    ratio = pTable[static_cast<int>(pan * PAN_TABLE_MAX + 0.5f)];
    if (info.centerZeroFlag) 
    {
        ratio /= pTable[PAN_TABLE_CENTER];
    }

    return info.zeroClampFlag ? ut::Clamp(ratio, 0.0f, 1.0f) : ut::Clamp(ratio, 0.0f, 2.0f);
}

f32 Util::CalcSurroundPanRatio(f32 pan, const PanInfo& rInfo) 
{
    pan = ut::Clamp(pan, 0.0f, 2.0f) / 2.0f;
    const f32* pTable = PanTableTable[rInfo.curve];

    f32 ratio = pTable[static_cast<int>(pan * PAN_TABLE_MAX + 0.5f)];
    return ut::Clamp(ratio, 0.0f, 2.0f);
}

const f32 Util::CALC_LPF_FREQ_INTERCEPT = 0.135614381f;
const u16 Util::CalcLpfFreqTable[CALC_LPF_FREQ_TABLE_SIZE] =
{
    80, 100, 128, 160, 200, 256, 320, 400, 500, 640, 800,
    1000, 1280, 1600, 2000, 2560, 3200, 4000, 5120, 6400,
    8000, 10240, 12800, 16000
};

f32 Util::CalcLpfFreq(f32 scale) 
{
    scale = ut::Clamp(scale, 0.0f, 1.0f);

    u16 freq = 0;

    if (scale < CALC_LPF_FREQ_INTERCEPT)
    {
        freq = CalcLpfFreqTable[0];
    }
    else if (scale >= 0.9f)
    {
        freq = CalcLpfFreqTable[CALC_LPF_FREQ_TABLE_SIZE-1];
    }
    else
    {
        int idx = static_cast<int>((scale-CALC_LPF_FREQ_INTERCEPT) / (0.1f/3));
        freq = CalcLpfFreqTable[idx];
    }

    return freq;
}

