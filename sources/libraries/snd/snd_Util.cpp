f32 Util::CalcPitchRatio(int pitch_) 
{
    register int octave = 0;

    while (pitch_ < 0)
    {
        octave--;
        pitch_ += SEMITONE_MAX * MICROTONE_MAX;
    }

    while (pitch_ >= SEMITONE_MAX * MICROTONE_MAX) 
    {
        octave++;
        pitch_ -= SEMITONE_MAX * MICROTONE_MAX;
    }

    register int note = pitch_ / MICROTONE_MAX;
    pitch_ %= MICROTONE_MAX;

    register f32 ratio = 1.0f;

    while (octave > 0) 
    {
        ratio *= 2.0f;
        octave--;
    }

    while (octave < 0) 
    {
        ratio /= 2.0f;
        octave++;
    }

    if (note != 0) 
    {
        ratio *= NoteTable[note];
    }
    if (pitch_ != 0) 
    {
        ratio *= PitchTable[pitch_];
    }

    return ratio;
}

f32 Util::CalcVolumeRatio(f32 dB) 
{
    dB = ut::Clamp(dB, -90.4f, 6.0f);
    return Decibel2RatioTable[-VOLUME_MIN + static_cast<int>(10 * dB)];
}

